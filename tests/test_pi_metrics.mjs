import assert from "node:assert/strict";
import {TokenRate} from "../Resources/agent-lantern.ts";

let monotonic = 0, wall = 1_792_000_000_000;
const rate = new TokenRate(() => monotonic, () => wall + monotonic);
rate.begin();
rate.observe(0);
monotonic = 1000; rate.observe(10);
assert.equal(rate.snapshot().live, undefined, "one usage report must not claim real-time TPS");
monotonic = 2000; rate.observe(30);
let live = rate.snapshot().live;
assert.equal((live.endCount - live.startCount) * 1000 / live.elapsedMs, 20);
rate.observe(30);
assert.equal(rate.samples.length, 2, "duplicate counters must not inflate TPS");
monotonic = 6001;
assert.equal(rate.snapshot().live, undefined, "stalled streams must stop displaying a live rate");
rate.observe(5);
assert.equal(rate.snapshot().live, undefined, "counter rollback requires a new baseline");
monotonic = 6501; rate.observe(15);
assert.equal(rate.snapshot().live.endCount, 15);
rate.finish(1000, 20000, true);
assert.equal(rate.snapshot().live, undefined);
assert.equal(rate.snapshot().recent.outputTokens * 1000 / rate.snapshot().recent.durationMs, 50);
monotonic += 30000;
rate.setPhase("tools");
assert.equal(rate.snapshot().recent.durationMs, 20000, "tool time must not dilute response TPS");
rate.reset(); rate.begin();
rate.observe(NaN); rate.observe(Infinity); rate.observe(-1);
assert.equal(rate.samples.length, 0);
rate.finish(100, undefined, true);
assert.equal(rate.snapshot().recent, undefined, "missing request duration must not produce a guessed average");
rate.finish(100, 1000, false);
assert.equal(rate.snapshot().recent, undefined, "errors and aborts must not produce a successful sample");
console.log("Pi TPS: actual counters, minimum sampling, duplicates, rollback, stale streams, response duration and tool-time exclusion: PASS");
